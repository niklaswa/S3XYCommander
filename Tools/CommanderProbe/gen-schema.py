#!/usr/bin/env python3
"""
Generates Sources/CommanderProbe/Schema.swift from the proto descriptors that were pulled out of
Enhauto's S3XY app (all_protos.txt, see the repo README §Reversing-Notes): the names and types of
every vehicle-data and vehicle-event field, every enum, the push types, and the read-only "Get"
requests the probe may send.

  python3 gen-schema.py ~/Downloads/s3xy-commander-ble-analysis/all_protos.txt
"""
import os, re, sys

src = open(sys.argv[1]).read()
files = re.split(r'^// file: ', src, flags=re.M)

enums = {}      # name -> {number: value name}; the first definition of a name wins
messages = {}   # name -> [(label, type, name, number)]


def blocks(text, keyword):
    """Top-level `keyword Name { ... }` blocks with balanced braces."""
    for m in re.finditer(rf'^{keyword} (\w+) \{{', text, flags=re.M):
        depth, i = 0, m.end() - 1
        while True:
            if text[i] == '{': depth += 1
            elif text[i] == '}':
                depth -= 1
                if depth == 0: break
            i += 1
        yield m.group(1), text[m.end():i]


for section in files:
    package = re.search(r'^package (\w+);', section, flags=re.M)
    prefix = package.group(1) + '.' if package else ''
    for name, body in blocks(section, 'enum'):
        values = {int(n): v for v, n in re.findall(r'(\w+) = (\d+);', body)}
        enums.setdefault(prefix + name, values)
        enums.setdefault(name, values)
    for name, body in blocks(section, 'message'):
        fields = re.findall(r'(repeated )?([\w.]+) (\w+) = (\d+);', body)
        messages.setdefault(name, [(l.strip(), t, n, int(num)) for l, t, n, num in fields])

# sint64 is zigzag like sint32 (Wire.render decodes it in 64 bits); the car's clock is one.
SCALARS = {'uint32': '.uint32', 'uint64': '.uint32', 'sint32': '.sint32', 'sint64': '.sint32', 'int32': '.int32',
           'float': '.float', 'double': '.double', 'string': '.string', 'bool': '.bool', 'bytes': '.bytes'}


def kind(t):
    if t in SCALARS: return SCALARS[t]
    if t in enums: return f'.enumeration("{t}")'
    return '.message'


def field_table(message):
    rows = []
    for _, t, n, num in sorted(messages[message], key=lambda f: f[3]):
        rows.append(f'        {num}: FieldInfo(name: "{n}", type: {kind(t)}),')
    return '\n'.join(rows)


used = set()
for message in ('PushVehicleDataHolder', 'PushVehicleEventsDataHolder'):
    for _, t, _, _ in messages[message]:
        if t in enums: used.add(t)
used |= {'EnhApiPushType', 'EnhApiMsgType', 'TeslaAPI.Status', 'TeslaAPI.ErrorState',
         'TeslaAPI.SessionDomain', 'TeslaAPI.SessionStatus', 'TeslaAPI.SessionErrorState',
         'TeslaAPI.UIStatus', 'Status'}

enum_lines = []
for name in sorted(used):
    values = ', '.join(f'{n}: "{v}"' for n, v in sorted(enums[name].items()))
    enum_lines.append(f'        "{name}": [{values}],')

# Read-only requests: "ReqGet…" whose message has no fields, with the payload field that carries
# them in EnhApiPayloadHolder and the message type that announces them.
holder = {t: num for _, t, _, num in messages['EnhApiPayloadHolder']}
msg_types = {v: n for n, v in enums['EnhApiMsgType'].items()}
gets = []
for name, fields in sorted(messages.items()):
    # The Dash's Wi-Fi password is the user's, not something to explore and log.
    if name.startswith('ReqGet') and not fields and name in holder and name != 'ReqGetWiFiSsidAndPass':
        mtype = msg_types.get('MType' + name)
        if mtype is None and name == 'ReqGetApiStatus': mtype = msg_types['MTypeReqGetTeslaAPIStatus']
        if mtype is not None:
            gets.append(f'        GetRequest(name: "{name}", msgType: {mtype}, payloadField: {holder[name]}),')

out = f'''// Generated by gen-schema.py from the Commander's proto descriptors. Do not edit.

enum ProtoType: Equatable {{
    case uint32, sint32, int32, float, double, string, bool, bytes, message
    case enumeration(String)
}}

struct FieldInfo {{
    let name: String
    let type: ProtoType
}}

struct GetRequest: Identifiable {{
    let name: String
    let msgType: UInt64
    let payloadField: Int
    var id: String {{ name }}
}}

enum Schema {{
    static let vehicleData: [UInt64: FieldInfo] = [
{field_table('PushVehicleDataHolder')}
    ]

    static let vehicleEvents: [UInt64: FieldInfo] = [
{field_table('PushVehicleEventsDataHolder')}
    ]

    static let enums: [String: [UInt64: String]] = [
{chr(10).join(enum_lines)}
    ]

    /// Requests without arguments that only read: safe to send while exploring.
    static let getRequests: [GetRequest] = [
{chr(10).join(gets)}
    ]
}}
'''
target = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'Sources/CommanderProbe/Schema.swift')
os.makedirs(os.path.dirname(target), exist_ok=True)
open(target, 'w').write(out)
print(f'{target}: {len(messages["PushVehicleDataHolder"])} vehicle fields, '
      f'{len(messages["PushVehicleEventsDataHolder"])} event fields, {len(used)} enums, {len(gets)} get requests')
